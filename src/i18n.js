export function isSupportedLang(id) {
  return Boolean(id) && Object.prototype.hasOwnProperty.call(dict, id);
}

export function detectInitialLanguage() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved && isSupportedLang(saved)) return saved;
  } catch (err) {}

  const nav = (typeof navigator !== 'undefined' && navigator.language) || '';
  const lower = nav.toLowerCase();
  if (lower.startsWith('zh')) {
    if (lower.includes('tw') || lower.includes('hk') || lower.includes('hant') || lower.includes('mo')) {
      return 'zh-TW';
    }
    return 'zh-CN';
  }
  if (lower.startsWith('ja')) return 'ja';
  return DEFAULT_LANG;
}

export function persistLanguage(lang) {
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch (err) {}
}

function lookup(lang, key) {
  if (isSupportedLang(lang) && Object.prototype.hasOwnProperty.call(dict[lang], key)) {
    return dict[lang][key];
  }
  if (Object.prototype.hasOwnProperty.call(dict.en, key)) return dict.en[key];
  if (Object.prototype.hasOwnProperty.call(dict[DEFAULT_LANG], key)) return dict[DEFAULT_LANG][key];
  return key;
}

export function translate(lang, key, vars) {
  let raw = lookup(lang, key);
  if (vars && typeof raw === 'string') {
    for (const [name, value] of Object.entries(vars)) {
      raw = raw.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
    }
  }
  return raw;
}

export function dictionaryKeys(lang) {
  return dict[lang] ? Object.keys(dict[lang]) : [];
}

export function createTranslator(lang) {
  return function t(key, vars) {
    return translate(lang, key, vars);
  };
}
